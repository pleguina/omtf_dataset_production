#!/usr/bin/env bash
set -euo pipefail

# run_first_validation_set.sh
#
# Staged CMS-facing validation flow for OMTF/GMT ML studies.
#
# What this script does now:
# 1) Uses the exact recommended sample order.
# 2) Pulls ONE representative file per dataset from DAS (smoke-first policy).
# 3) Collects DAS summary/site/file metadata for each candidate.
# 4) Generates one markdown table per sample plus a consolidated report.
#
# What this script does not force:
# - It does not hardcode your cmsRun chain command.
# - It leaves run-time metrics (windows, efficiencies, model/current ratio, etc.)
#   as TODO fields to be filled after your ntuplizer/model jobs.

if ! command -v dasgoclient >/dev/null 2>&1; then
  echo "[ERROR] dasgoclient not found"
  echo "Run: source /cvmfs/cms.cern.ch/cmsset_default.sh"
  exit 1
fi

if ! dasgoclient --query='site dataset=/MinBias_TuneCP5_14TeV-pythia8/Phase2Spring24DIGIRECOMiniAOD-PU140_Trk1GeV_140X_mcRun4_realistic_v4-v1/GEN-SIM-DIGI-RAW-MINIAOD' >/dev/null 2>&1; then
  echo "[WARN] DAS query failed. Check proxy (voms-proxy-init) and X509_USER_PROXY."
fi

STAMP="$(date +%Y%m%d_%H%M%S)"
OUTBASE="/afs/cern.ch/user/p/pleguina/omtf_hecin_dataset_production/smoke_results/first_validation_${STAMP}"
mkdir -p "${OUTBASE}"

# Validation order requested by user.
ORDER=(
  minbias
  displaced_midpt
  displaced_lowpt
  dy_prompt
  llp_addon
)

declare -A DATASET
declare -A CAMPAIGN
declare -A CMSSW_TAG
declare -A SAMPLE_ROLE

DATASET[minbias]='/MinBias_TuneCP5_14TeV-pythia8/Phase2Spring24DIGIRECOMiniAOD-PU140_Trk1GeV_140X_mcRun4_realistic_v4-v1/GEN-SIM-DIGI-RAW-MINIAOD'
CAMPAIGN[minbias]='Phase2Spring24DIGIRECOMiniAOD'
CMSSW_TAG[minbias]='140X_mcRun4_realistic_v4'
SAMPLE_ROLE[minbias]='Background/rate proxy (first smoke sample)'

DATASET[displaced_midpt]='/DisplacedMuons_Pt-10To30_Dxy-0To3000-gun/Phase2Fall22DRMiniAOD-PU200_125X_mcRun4_realistic_v2-v1/GEN-SIM-DIGI-RAW-MINIAOD'
CAMPAIGN[displaced_midpt]='Phase2Fall22DRMiniAOD'
CMSSW_TAG[displaced_midpt]='125X_mcRun4_realistic_v2'
SAMPLE_ROLE[displaced_midpt]='Displaced controlled medium-pT'

DATASET[displaced_lowpt]='/DisplacedMuons_Pt-2To10_Dxy-0To3000-gun/Phase2Fall22DRMiniAOD-PU200_125X_mcRun4_realistic_v2-v1/GEN-SIM-DIGI-RAW-MINIAOD'
CAMPAIGN[displaced_lowpt]='Phase2Fall22DRMiniAOD'
CMSSW_TAG[displaced_lowpt]='125X_mcRun4_realistic_v2'
SAMPLE_ROLE[displaced_lowpt]='Displaced controlled low-pT (stress test)'

DATASET[dy_prompt]='/DYToLL_M-10To50_TuneCP5_14TeV-pythia8/Phase2Spring23DIGIRECOMiniAOD-PU200_Trk1GeV_131X_mcRun4_realistic_v5-v1/GEN-SIM-DIGI-RAW-MINIAOD'
CAMPAIGN[dy_prompt]='Phase2Spring23DIGIRECOMiniAOD'
CMSSW_TAG[dy_prompt]='131X_mcRun4_realistic_v5'
SAMPLE_ROLE[dy_prompt]='Realistic prompt (different campaign)'

DATASET[llp_addon]='/HTo2LongLivedTo2mu2jets_MH-125_MFF-20_CTau-1300mm_TuneCP5_14TeV_pythia8/Phase2Spring24DIGIRECOMiniAOD-PU200_Trk1GeV_140X_mcRun4_realistic_v4-v1/GEN-SIM-DIGI-RAW-MINIAOD'
CAMPAIGN[llp_addon]='Phase2Spring24DIGIRECOMiniAOD'
CMSSW_TAG[llp_addon]='140X_mcRun4_realistic_v4'
SAMPLE_ROLE[llp_addon]='LLP external validation add-on'

CONSOLIDATED="${OUTBASE}/FIRST_VALIDATION_REPORT.md"

cat > "${CONSOLIDATED}" <<'EOF'
# First Validation Report (Staged, 1-file smoke first)

This report is generated by `scripts/run_first_validation_set.sh`.

Validation policy:
- Do not start with all samples.
- Start from 1 representative file per dataset.
- Confirm chain viability before performance scans.

Required output branches/products:
- OMTFAllInputTree
- OMTFHitsTree
- MuonStubTps
- MuonStubKmtf
- GenMuon

EOF

for key in "${ORDER[@]}"; do
  ds="${DATASET[$key]}"
  role="${SAMPLE_ROLE[$key]}"
  campaign="${CAMPAIGN[$key]}"
  cmssw_tag="${CMSSW_TAG[$key]}"

  sample_dir="${OUTBASE}/${key}"
  mkdir -p "${sample_dir}"

  echo "=== ${key} ==="
  echo "Dataset: ${ds}"

  dasgoclient --query="summary dataset=${ds}" > "${sample_dir}/summary.txt"
  dasgoclient --query="site dataset=${ds}" > "${sample_dir}/sites.txt"
  dasgoclient --query="file dataset=${ds}" --limit=1 > "${sample_dir}/files_1.txt"
  dasgoclient --query="file dataset=${ds}" --limit=10 > "${sample_dir}/files_10.txt"

  one_file="$(head -n 1 "${sample_dir}/files_1.txt" || true)"
  nevents="$(python3 - <<PYEOF
import json
from pathlib import Path
p = Path('${sample_dir}/summary.txt')
txt = p.read_text().strip()
if not txt:
    print('UNKNOWN')
else:
    try:
        j = json.loads(txt)
        print(j[0].get('nevents', j[0].get('num_event', 'UNKNOWN')))
    except Exception:
        print('UNKNOWN')
PYEOF
)"
  nfiles="$(python3 - <<PYEOF
import json
from pathlib import Path
p = Path('${sample_dir}/summary.txt')
txt = p.read_text().strip()
if not txt:
    print('UNKNOWN')
else:
    try:
        j = json.loads(txt)
        print(j[0].get('nfiles', j[0].get('num_file', 'UNKNOWN')))
    except Exception:
        print('UNKNOWN')
PYEOF
)"
  sites="$(paste -sd ', ' "${sample_dir}/sites.txt" 2>/dev/null || true)"
  if [[ -z "${sites}" ]]; then
    sites="UNKNOWN"
  fi

  sample_md="${sample_dir}/QUALIFICATION_${key}.md"
  cat > "${sample_md}" <<EOF
# Sample Qualification: ${key}

## Dataset

- Role: ${role}
- Dataset: ${ds}
- Campaign: ${campaign}
- CMSSW/GT inferred tag: ${cmssw_tag}

## One-file smoke input

- Representative file from DAS:
  - ${one_file}

## Qualification table

| Field | Value |
|---|---|
| dataset name | ${ds} |
| campaign | ${campaign} |
| CMSSW release / GT inferred | ${cmssw_tag} |
| number of files processed | 1 (smoke target) |
| number of events (dataset summary) | ${nevents} |
| number of OMTF/TPS windows | TODO (fill after ntuplizer run) |
| mean processors per event | TODO (fill after ntuplizer run) |
| fraction of muons in OMTF overlap | TODO (fill after ntuplizer run) |
| model efficiency | TODO (fill after model eval) |
| current OMTF/GMT efficiency | TODO (fill after reference eval) |
| model / current ratio | TODO |
| background accept (if applicable) | TODO |
| sites | ${sites} |
| lxplus file accessibility | TODO (xrdcp/xrdfs/cmsRun test) |
| enough info to rerun L1 | TODO (must be proven by cmsRun output branches) |

## Required branch checklist

- [ ] OMTFAllInputTree
- [ ] OMTFHitsTree
- [ ] MuonStubTps
- [ ] MuonStubKmtf
- [ ] GenMuon

## Raw DAS metadata files

- summary: summary.txt
- sites: sites.txt
- one file: files_1.txt
- ten files: files_10.txt
EOF

  cat >> "${CONSOLIDATED}" <<EOF
## ${key}

- Role: ${role}
- Dataset: ${ds}
- Campaign: ${campaign}
- CMSSW/GT inferred: ${cmssw_tag}
- One-file smoke input: ${one_file}
- Per-sample report: ${sample_md}

| Field | Value |
|---|---|
| number of files processed | 1 (smoke target) |
| number of events (dataset summary) | ${nevents} |
| number of files (dataset summary) | ${nfiles} |
| sites | ${sites} |
| OMTFAllInputTree | TODO |
| OMTFHitsTree | TODO |
| MuonStubTps | TODO |
| MuonStubKmtf | TODO |
| GenMuon | TODO |
| model efficiency | TODO |
| current OMTF/GMT efficiency | TODO |
| model/current ratio | TODO |

EOF
done

cat <<EOF

=== First validation set prepared ===
Output directory: ${OUTBASE}
Consolidated report: ${CONSOLIDATED}

Next step:
1) Run 1-file cmsRun ntuplizer/emulator per sample.
2) Tick required branch checklist in each QUALIFICATION_*.md.
3) Fill model/current efficiency fields.
EOF
