#!/usr/bin/env bash
set -euo pipefail

# Build a disk-only first-validation report (1-file smoke targets) without
# touching the original first_validation report artifacts.

BASEDIR="/afs/cern.ch/user/p/pleguina/omtf_hecin_dataset_production"
OUTDIR="${BASEDIR}/smoke_results/first_validation_disk_$(date +%Y%m%d_%H%M%S)"
REPORT="${OUTDIR}/FIRST_VALIDATION_DISK_REPORT.md"
PROBE_XRD=false

if [[ "${1:-}" == "--probe-xrd" ]]; then
  PROBE_XRD=true
fi

if ! command -v dasgoclient >/dev/null 2>&1; then
  echo "ERROR: dasgoclient not found"
  exit 1
fi

mkdir -p "${OUTDIR}"

# key|role|dataset|campaign|cmssw_gt|one_file
SPECS=$(cat <<'EOF'
minbias|Background/rate proxy (disk replicas present)|/MinBias_TuneCP5_14TeV-pythia8/Phase2Spring24DIGIRECOMiniAOD-PU140_Trk1GeV_140X_mcRun4_realistic_v4-v1/GEN-SIM-DIGI-RAW-MINIAOD|Phase2Spring24DIGIRECOMiniAOD|140X_mcRun4_realistic_v4|/store/mc/Phase2Spring24DIGIRECOMiniAOD/MinBias_TuneCP5_14TeV-pythia8/GEN-SIM-DIGI-RAW-MINIAOD/PU140_Trk1GeV_140X_mcRun4_realistic_v4-v1/120000/a7bb849a-2434-4c23-836e-ebaaafdc5f2d.root
displaced_lowpt|Displaced controlled low-pT (disk)|/DisplacedMuons_Pt-2To10_Dxy-0To3000-gun/Phase2Spring24DIGIRECOMiniAOD-PU200_Trk1GeV_140X_mcRun4_realistic_v4-v1/GEN-SIM-DIGI-RAW-MINIAOD|Phase2Spring24DIGIRECOMiniAOD|140X_mcRun4_realistic_v4|/store/mc/Phase2Spring24DIGIRECOMiniAOD/DisplacedMuons_Pt-2To10_Dxy-0To3000-gun/GEN-SIM-DIGI-RAW-MINIAOD/PU200_Trk1GeV_140X_mcRun4_realistic_v4-v1/130000/3acd9ce2-a987-4192-9e96-d9050add5eb2.root
displaced_midpt|Displaced controlled medium-pT (disk)|/DisplacedMuons_Pt-10To30_Dxy-0To3000-gun/Phase2Spring24DIGIRECOMiniAOD-PU200_Trk1GeV_140X_mcRun4_realistic_v4-v1/GEN-SIM-DIGI-RAW-MINIAOD|Phase2Spring24DIGIRECOMiniAOD|140X_mcRun4_realistic_v4|/store/mc/Phase2Spring24DIGIRECOMiniAOD/DisplacedMuons_Pt-10To30_Dxy-0To3000-gun/GEN-SIM-DIGI-RAW-MINIAOD/PU200_Trk1GeV_140X_mcRun4_realistic_v4-v1/2810000/4c5da4c2-0307-4e29-b55c-3eb069c98342.root
dy_prompt|Realistic prompt validation (disk)|/DYToLL_M-10To50_TuneCP5_14TeV-pythia8/Phase2Spring24DIGIRECOMiniAOD-PU200_Trk1GeV_140X_mcRun4_realistic_v4-v1/GEN-SIM-DIGI-RAW-MINIAOD|Phase2Spring24DIGIRECOMiniAOD|140X_mcRun4_realistic_v4|/store/mc/Phase2Spring24DIGIRECOMiniAOD/DYToLL_M-10To50_TuneCP5_14TeV-pythia8/GEN-SIM-DIGI-RAW-MINIAOD/PU200_Trk1GeV_140X_mcRun4_realistic_v4-v1/2560000/5a7d75f3-dcc2-483c-a840-0d66fbd1acbe.root
llp_addon|LLP external add-on (4mu disk substitute)|/HTo2LongLivedTo4mu_MH-125_MFF-12_CTau-900mm_TuneCP5_14TeV-pythia8/Phase2Spring24DIGIRECOMiniAOD-PU200_Trk1GeV_140X_mcRun4_realistic_v4-v1/GEN-SIM-DIGI-RAW-MINIAOD|Phase2Spring24DIGIRECOMiniAOD|140X_mcRun4_realistic_v4|/store/mc/Phase2Spring24DIGIRECOMiniAOD/HTo2LongLivedTo4mu_MH-125_MFF-12_CTau-900mm_TuneCP5_14TeV-pythia8/GEN-SIM-DIGI-RAW-MINIAOD/PU200_Trk1GeV_140X_mcRun4_realistic_v4-v1/2530000/92ddf443-bd16-445d-a951-0440c576434f.root
EOF
)

cat > "${REPORT}" <<EOF
# First Validation Report (Disk-Only, 1-file smoke first)

This report is generated by scripts/run_first_validation_disk_set.sh.

Policy:
- Use only datasets with known disk replicas.
- Keep one-file smoke targets.
- Do not modify original first_validation report artifacts.

Required output branches/products:
- OMTFAllInputTree
- OMTFHitsTree
- MuonStubTps
- MuonStubKmtf
- GenMuon

EOF

while IFS='|' read -r key role dataset campaign gt one_file; do
  [[ -z "${key}" ]] && continue

  summary=$(dasgoclient --query="summary dataset=${dataset}" 2>/dev/null || true)
  events=$(echo "${summary}" | sed -n 's/.*nevents"[[:space:]]*:[[:space:]]*\([0-9][0-9]*\).*/\1/p' | head -1)
  files=$(echo "${summary}" | sed -n 's/.*nfiles"[[:space:]]*:[[:space:]]*\([0-9][0-9]*\).*/\1/p' | head -1)
  [[ -z "${events}" ]] && events="unknown"
  [[ -z "${files}" ]] && files="unknown"

  sites=$(dasgoclient --query="site dataset=${dataset}" 2>/dev/null | tr ' ' '\n' | sed '/^$/d' | sort -u | tr '\n' ',' | sed 's/,$//')
  [[ -z "${sites}" ]] && sites="unknown"

  xrd_status="SKIP"
  if [[ "${PROBE_XRD}" == "true" ]]; then
    if timeout 20s xrdfs root://cms-xrd-global.cern.ch stat "${one_file}" >/dev/null 2>&1; then
      xrd_status="OK"
    else
      xrd_status="FAIL"
    fi
  fi

  cat >> "${REPORT}" <<EOF
## ${key}

- Role: ${role}
- Dataset: ${dataset}
- Campaign: ${campaign}
- CMSSW/GT inferred: ${gt}
- One-file smoke input: ${one_file}

| Field | Value |
|---|---|
| number of files processed | 1 (smoke target) |
| number of events (dataset summary) | ${events} |
| number of files (dataset summary) | ${files} |
| sites | ${sites} |
| xrd probe (optional) | ${xrd_status} |
| OMTFAllInputTree | TODO |
| OMTFHitsTree | TODO |
| MuonStubTps | TODO |
| MuonStubKmtf | TODO |
| GenMuon | TODO |
| model efficiency | TODO |
| current OMTF/GMT efficiency | TODO |
| model/current ratio | TODO |

EOF

done <<< "${SPECS}"

echo "Generated disk-only report: ${REPORT}"
if [[ "${PROBE_XRD}" == "true" ]]; then
  echo "XRootD probing was enabled."
else
  echo "Tip: rerun with --probe-xrd to include redirector probe status."
fi
