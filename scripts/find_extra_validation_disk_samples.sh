#!/usr/bin/env bash
set -euo pipefail

# Search extra validation classes and keep candidates with at least one _Disk site.

BASEDIR="/afs/cern.ch/user/p/pleguina/omtf_hecin_dataset_production"
OUTDIR="${BASEDIR}/smoke_results/extra_validation_disk_$(date +%Y%m%d_%H%M%S)"
REPORT="${OUTDIR}/EXTRA_VALIDATION_DISK_REPORT.md"
MATCH_MODE="phase2"

if [[ "${1:-}" == "--run4" ]]; then
  MATCH_MODE="run4"
elif [[ -n "${1:-}" && "${1}" != "--phase2" ]]; then
  echo "Usage: $0 [--phase2|--run4]"
  exit 1
fi

if ! command -v dasgoclient >/dev/null 2>&1; then
  echo "ERROR: dasgoclient not found"
  exit 1
fi

mkdir -p "${OUTDIR}"

# Query set: default Phase2 mode or Run4 mode.
declare -A QUERY
if [[ "${MATCH_MODE}" == "phase2" ]]; then
  QUERY[qcd_pu200]='dataset dataset=/QCD*/*Phase2*PU200*/*GEN-SIM-DIGI-RAW-MINIAOD*'
  QUERY[ttbar_pu200]='dataset dataset=/TT*/*Phase2*PU200*/*GEN-SIM-DIGI-RAW-MINIAOD*'
  QUERY[singlemuon_highpt]='dataset dataset=/SingleMuon_Pt-200To500*/*Phase2*PU200*/*GEN-SIM-DIGI-RAW-MINIAOD*'
else
  # Keep PU200 scope broad, then filter for Run4/mcRun4 in returned dataset names.
  QUERY[qcd_pu200]='dataset dataset=/QCD*/*PU200*/*GEN-SIM-DIGI-RAW-MINIAOD*'
  QUERY[ttbar_pu200]='dataset dataset=/TT*/*PU200*/*GEN-SIM-DIGI-RAW-MINIAOD*'
  QUERY[singlemuon_highpt]='dataset dataset=/SingleMuon_Pt-200To500*/*PU200*/*GEN-SIM-DIGI-RAW-MINIAOD*'
fi

declare -A LIMIT
LIMIT[qcd_pu200]=100
LIMIT[ttbar_pu200]=100
LIMIT[singlemuon_highpt]=50

cat > "${REPORT}" <<EOF
# Extra Validation Classes (Disk-Accessible Candidates)

Generated by scripts/find_extra_validation_disk_samples.sh.

Selection rule:
- Keep dataset only if at least one replica site name ends in _Disk.
- Match mode: ${MATCH_MODE}

EOF

for key in qcd_pu200 ttbar_pu200 singlemuon_highpt; do
  q="${QUERY[$key]}"
  lim="${LIMIT[$key]}"

  all_file="${OUTDIR}/${key}_all.txt"
  disk_file="${OUTDIR}/${key}_disk.txt"

  dasgoclient --query="${q}" --limit="${lim}" | sed '/^$/d' | sort -u > "${all_file}.tmp"
  if [[ "${MATCH_MODE}" == "run4" ]]; then
    grep -Ei 'run4|mcRun4' "${all_file}.tmp" > "${all_file}" || true
  else
    mv "${all_file}.tmp" "${all_file}"
  fi
  rm -f "${all_file}.tmp"
  : > "${disk_file}"

  while IFS= read -r ds; do
    [[ -z "${ds}" ]] && continue

    sites=$(dasgoclient --query="site dataset=${ds}" 2>/dev/null | tr ' ' '\n' | sed '/^$/d' | sort -u)
    disk_sites=$(echo "${sites}" | grep '_Disk$' || true)

    if [[ -n "${disk_sites}" ]]; then
      one_file=$(dasgoclient --query="file dataset=${ds}" --limit=1 2>/dev/null | head -1)
      [[ -z "${one_file}" ]] && one_file="N/A"

      {
        echo "DATASET|${ds}"
        echo "DISK_SITES|$(echo "${disk_sites}" | tr '\n' ',' | sed 's/,$//')"
        echo "ONE_FILE|${one_file}"
        echo
      } >> "${disk_file}"
    fi
  done < "${all_file}"

  total=$(wc -l < "${all_file}" | tr -d ' ')
  disk_count=$(grep -c '^DATASET|' "${disk_file}" || true)

  cat >> "${REPORT}" <<EOF
## ${key}

- Query: ${q}
- Limit: ${lim}
- Total candidates returned: ${total}
- Disk-accessible candidates (_Disk): ${disk_count}
- Raw list: ${all_file}
- Disk-filtered list: ${disk_file}

| Dataset | _Disk sites | One file |
|---|---|---|
EOF

  while IFS= read -r line; do
    [[ "${line}" == DATASET\|* ]] || continue
    ds="${line#DATASET|}"
    IFS= read -r dline || true
    IFS= read -r fline || true
    IFS= read -r _blank || true
    dsites="${dline#DISK_SITES|}"
    onef="${fline#ONE_FILE|}"
    echo "| ${ds} | ${dsites} | ${onef} |" >> "${REPORT}"
  done < "${disk_file}"

  echo >> "${REPORT}"
done

echo "Generated extra-validation report: ${REPORT}"
